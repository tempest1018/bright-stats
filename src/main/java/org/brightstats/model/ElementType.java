package org.brightstats.model;
import java.util.*;
/** Independent typed schema using mapped element identifiers; registration is not numerical parity. */
public enum ElementType {
    MODERATING_EFFECT(Role.LEGACY,Family.PLS,Family.REGRESSION,Family.PROCESS,Family.CBSEM,Family.GSCA),
    GENERIC_MANIFEST_VARIABLE(Role.LEGACY,Family.PLS,Family.REGRESSION,Family.PROCESS,Family.CBSEM,Family.GSCA),
    ROOT(Role.CONTAINER,Family.PLS,Family.REGRESSION,Family.PROCESS,Family.CBSEM,Family.GSCA),
    DONGLE(Role.ANCHOR,Family.PLS,Family.REGRESSION,Family.PROCESS,Family.CBSEM,Family.GSCA),
    LATENT_VARIABLE(Role.NODE,Family.PLS),
    QUADRATIC_EFFECT(Role.NODE,Family.PLS,Family.GSCA),
    GAUSSIAN_COPULA(Role.NODE,Family.PLS,Family.REGRESSION,Family.PROCESS,Family.GSCA),
    STANDARD_MANIFEST_VARIABLE(Role.NODE,Family.PLS),
    POSTIT(Role.ANNOTATION,Family.PLS,Family.REGRESSION,Family.PROCESS,Family.CBSEM,Family.GSCA),
    CONNECTION_BETWEEN_LV_AND_LV(Role.CONNECTION,Family.PLS),
    CONNECTION_BETWEEN_GAUSSIAN_COPULA_AND_INDEPENT_TO_DEPENDENT_LV_CONNECTION(Role.CONNECTION,Family.PLS,Family.REGRESSION,Family.GSCA,Family.PROCESS),
    CONNECTION_FOR_PLS_MODERATION(Role.CONNECTION,Family.PLS),
    CONNECTION_FOR_GSCA_MODERATION(Role.CONNECTION,Family.GSCA),
    CONNECTION_BETWEEN_QUADRATIC_EFFECT_AND_INDEPENT_TO_DEPENDENT_LV_CONNECTION(Role.CONNECTION,Family.PLS,Family.GSCA),
    CONNECTION_BETWEEN_LV_AND_MV(Role.CONNECTION,Family.PLS),
    CONNECTION_BETWEEN_PROCESS_LV_AND_PROCESS_LV(Role.CONNECTION,Family.PROCESS),
    CONNECTION_BETWEEN_PROCESS_LV_AND_PROCESS_CV(Role.CONNECTION,Family.PROCESS),
    CONNECTION_BETWEEN_PROCESS_QUADRATIC_EFFECT_AND_INDEPENT_TO_DEPENDENT_LV_CONNECTION(Role.CONNECTION,Family.PROCESS),
    CONNECTION_FOR_PROCESS_MODERATION(Role.CONNECTION,Family.PROCESS),
    CONNECTION_BETWEEN_PROCESS_LV_AND_PROCESS_MV(Role.CONNECTION,Family.PROCESS),
    CONNECTION_BETWEEN_PROCESS_CV_AND_PROCESS_MV(Role.CONNECTION,Family.PROCESS),
    REGRESSION_INTERCEPT(Role.NODE,Family.REGRESSION),
    REGRESSION_INDEPENDENT_VARIABLE(Role.NODE,Family.REGRESSION),
    REGRESSION_DEPENDENT_VARIABLE(Role.NODE,Family.REGRESSION),
    CONNECTION_BETWEEN_DEPENDENT_AND_INDEPENDENT_VARIABLE(Role.CONNECTION,Family.REGRESSION),
    CONNECTION_BETWEEN_DEPENDENT_AND_INTERCEPT(Role.CONNECTION,Family.REGRESSION),
    PROCESS_MODEL_CONTROL_VARIABLE(Role.NODE,Family.PROCESS),
    PROCESS_MODEL_LATENT_VARIABLE(Role.NODE,Family.PROCESS),
    PROCESS_MODEL_QUADRATIC_EFFECT(Role.NODE,Family.PROCESS),
    PROCESS_MODEL_STANDARD_MANIFEST_VARIABLE(Role.NODE,Family.PROCESS),
    CBSEM_LATENT_VARIABLE(Role.NODE,Family.CBSEM),
    CBSEM_ERROR_TERM(Role.NODE,Family.CBSEM),
    CBSEM_STANDARD_MANIFEST_VARIABLE(Role.NODE,Family.CBSEM),
    CBSEM_CONNECTION_FOR_MODERATION(Role.CONNECTION,Family.CBSEM),
    CBSEM_CONNECTION_BETWEEN_LV_AND_LV(Role.CONNECTION,Family.CBSEM),
    CBSEM_CONNECTION_BETWEEN_LV_AND_MV(Role.CONNECTION,Family.CBSEM),
    CBSEM_CONNECTION_BETWEEN_MV_AND_MV(Role.CONNECTION,Family.CBSEM),
    CBSEM_CONNECTION_BETWEEN_MV_AND_ERROR_TERM(Role.CONNECTION,Family.CBSEM),
    CBSEM_CONNECTION_BETWEEN_LV_AND_ERROR_TERM(Role.CONNECTION,Family.CBSEM),
    CBSEM_CORRELATION_CONNECTION_BETWEEN_LV_AND_LV(Role.CONNECTION,Family.CBSEM),
    CBSEM_CORRELATION_CONNECTION_BETWEEN_LV_AND_MV(Role.CONNECTION,Family.CBSEM),
    CBSEM_CORRELATION_CONNECTION_BETWEEN_MV_AND_MV(Role.CONNECTION,Family.CBSEM),
    CBSEM_CORRELATION_CONNECTION_BETWEEN_ERROR_TERM_AND_ERROR_TERM(Role.CONNECTION,Family.CBSEM),
    CBSEM_CORRELATION_CONNECTION_BETWEEN_ERROR_TERM_AND_LV(Role.CONNECTION,Family.CBSEM),
    CBSEM_CORRELATION_CONNECTION_BETWEEN_ERROR_TERM_AND_MV(Role.CONNECTION,Family.CBSEM),
    GSCA_LATENT_VARIABLE(Role.NODE,Family.GSCA),
    GSCA_STANDARD_MANIFEST_VARIABLE(Role.NODE,Family.GSCA),
    GSCA_CONNECTION_BETWEEN_LV_AND_LV(Role.CONNECTION,Family.GSCA),
    GSCA_CONNECTION_BETWEEN_LV_AND_MV(Role.CONNECTION,Family.GSCA),
    CONNECTION_LABEL(Role.ANNOTATION,Family.PLS,Family.REGRESSION,Family.PROCESS,Family.CBSEM,Family.GSCA),
    NODE_EXTERNAL_LABEL(Role.ANNOTATION,Family.PLS,Family.REGRESSION,Family.PROCESS,Family.CBSEM,Family.GSCA);
    public enum Family {PLS,REGRESSION,PROCESS,CBSEM,GSCA}
    public enum Role {CONTAINER,ANCHOR,NODE,CONNECTION,ANNOTATION,LEGACY}
    private final Role role;private final Set<Family> families;
    ElementType(Role role,Family... families){this.role=role;this.families=Set.of(families);}
    public Role role(){return role;}
    public boolean supports(Family family){return families.contains(family);}
    public boolean measurement(){return switch(this){case CONNECTION_BETWEEN_LV_AND_MV,CONNECTION_BETWEEN_PROCESS_LV_AND_PROCESS_MV,CONNECTION_BETWEEN_PROCESS_CV_AND_PROCESS_MV,CBSEM_CONNECTION_BETWEEN_LV_AND_MV,GSCA_CONNECTION_BETWEEN_LV_AND_MV->true;default->false;};}
    public boolean structural(){return switch(this){case CONNECTION_BETWEEN_LV_AND_LV,CONNECTION_BETWEEN_PROCESS_LV_AND_PROCESS_LV,CONNECTION_BETWEEN_PROCESS_LV_AND_PROCESS_CV,CONNECTION_BETWEEN_DEPENDENT_AND_INDEPENDENT_VARIABLE,CBSEM_CONNECTION_BETWEEN_LV_AND_LV,CBSEM_CONNECTION_BETWEEN_MV_AND_MV,GSCA_CONNECTION_BETWEEN_LV_AND_LV->true;default->false;};}
    public boolean modifier(){return role==Role.CONNECTION&&(name().contains("MODERATION")||name().contains("BETWEEN_GAUSSIAN_COPULA")||name().contains("BETWEEN_QUADRATIC_EFFECT")||name().contains("BETWEEN_PROCESS_QUADRATIC_EFFECT"));}
    public boolean covariance(){return name().startsWith("CBSEM_CORRELATION_");}
    public boolean observed(){return switch(this){case STANDARD_MANIFEST_VARIABLE,PROCESS_MODEL_STANDARD_MANIFEST_VARIABLE,CBSEM_STANDARD_MANIFEST_VARIABLE,GSCA_STANDARD_MANIFEST_VARIABLE,GENERIC_MANIFEST_VARIABLE,REGRESSION_INDEPENDENT_VARIABLE,REGRESSION_DEPENDENT_VARIABLE->true;default->false;};}
    public boolean latent(){return switch(this){case LATENT_VARIABLE,PROCESS_MODEL_LATENT_VARIABLE,PROCESS_MODEL_CONTROL_VARIABLE,CBSEM_LATENT_VARIABLE,GSCA_LATENT_VARIABLE->true;default->false;};}
}
